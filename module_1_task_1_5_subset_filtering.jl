using DataFrames

sales_df = DataFrame(
    product = ["Ноутбук", "Монитор", "Клавиатура", "Мышь"],
    qty = [2, 5, 10, 15],
    price = [85_000.0, 24_000.0, 4_500.0, 2_200.0]
)

mid_segment = subset(
    sales_df,
    :qty => (q -> q .>= 5),
    :price => (p -> p .< 30_000.0)
)

println(mid_segment)

@assert nrow(mid_segment) == 3 "В выборке должно остаться 3 строки!"
@assert mid_segment.product == ["Монитор", "Клавиатура", "Мышь"] "Неверный состав отфильтрованных товаров!"
