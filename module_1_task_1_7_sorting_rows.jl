using DataFrames

sales_df = DataFrame(
    product = ["Ноутбук", "Монитор", "Клавиатура", "Мышь"],
    qty = [2, 5, 10, 15],
    price = [85_000.0, 24_000.0, 4_500.0, 2_200.0]
)

sales_by_qty_desc = sort(
    sales_df,
    order(:qty, rev = true)
)

println(sales_by_qty_desc)

@assert sales_by_qty_desc.product[1] == "Мышь" "Первой должна идти позиция с максимальным количеством!"
@assert sales_by_qty_desc.qty == [15, 10, 5, 2] "Неверный порядок сортировки по количеству!"
