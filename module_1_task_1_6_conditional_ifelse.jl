using DataFrames

sales_df = DataFrame(
    product = ["Ноутбук", "Монитор", "Клавиатура", "Мышь"],
    qty = [2, 5, 10, 15],
    price = [85_000.0, 24_000.0, 4_500.0, 2_200.0]
)

sales_segmented = transform(
    sales_df,
    :price => (p -> ifelse.(p .>= 20_000.0, "Премиум", "Масс-маркет")) => :segment,
    :qty => (q -> ifelse.(q .>= 10, 0.10, 0.0)) => :discount
)

println(sales_segmented)

@assert sales_segmented.segment == ["Премиум", "Премиум", "Масс-маркет", "Масс-маркет"] "Неверная сегментация товаров!"
@assert sum(sales_segmented.discount) == 0.20 "Неверная сумма ставок скидки!"
