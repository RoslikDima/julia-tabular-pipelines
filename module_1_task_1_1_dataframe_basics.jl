using DataFrames

sales_df = DataFrame(
    product = ["Ноутбук", "Монитор", "Клавиатура", "Мышь"],
    qty = [2, 5, 10, 15],
    price = [85_000.0, 24_000.0, 4_500.0, 2_200.0]
)

println(sales_df)
println("Кол-во строк в датафрейме: ", nrow(sales_df))
println("Кол-во столбцов в датафрейме: ", ncol(sales_df))
println("Имена столбцов: ", names(sales_df))
println("Типы столбцов: ", eltype.(eachcol(sales_df)))

@assert nrow(sales_df) == 4 && ncol(sales_df) == 3 "Неверная размерность таблицы!"
